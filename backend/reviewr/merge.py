"""Update a PR branch from its base branch (usually main), one conflict at a time.

The flow mirrors review comments: preview, triage, resolve, finish.

- Preview: `git merge-tree` works out which files would conflict without touching any
  checkout.
- Start: the merge runs in a throwaway worktree, <root>/merge/tree, detached at your
  checkout's HEAD (so unpushed Fix commits are included). Your checkout is not touched.
  Each conflicted region becomes a Conflict. Simple ones are classified by rule here;
  the AI triages the rest and proposes code where neither side alone is right.
- Resolve: you pick an option for each conflict (keep the PR's side, take main's, keep
  both, the AI's proposal, or your own edit). Nothing is written to your branch yet.
- Finish: the resolved files are written, optional checks run on them, and the merge
  is committed in the throwaway worktree. Your checkout is then fast-forwarded to that
  commit, which fails safely if you have uncommitted edits to the same files. Pushing is
  a separate, explicit step.
"""

from __future__ import annotations

import logging
import re
import shutil
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from datetime import UTC, datetime
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field

from reviewr import fixwork, git
from reviewr.checks import CheckReport, run_checks
from reviewr.config import Config
from reviewr.fixwork import _failed_report
from reviewr.models import PullRequest

log = logging.getLogger(__name__)

Category = Literal["auto", "input", "propose"]
Option = Literal["ours", "theirs", "ours_then_theirs", "theirs_then_ours", "proposal", "custom", "delete"]
Kind = Literal["text", "deleted_in_pr", "deleted_in_main", "binary", "lockfile"]

# Regenerated by package managers; resolved per file rather than per hunk.
LOCKFILES = {
    "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "uv.lock",
    "poetry.lock", "Pipfile.lock", "Cargo.lock", "Gemfile.lock", "composer.lock", "go.sum",
}
CONTEXT_LINES = 6
FETCH_INTERVAL_S = 300

_lock = threading.RLock()
_executor = ThreadPoolExecutor(max_workers=1, thread_name_prefix="merge")
_last_fetch: dict[tuple[str, str], float] = {}
_jobs: set[str] = set()  # sessions with a triage or checks job running in this process


class MergeError(RuntimeError):
    pass


class Commit(BaseModel):
    sha: str
    author: str = ""
    subject: str


class Conflict(BaseModel):
    id: str
    path: str
    index: int  # position among this file's conflicts, from 0
    kind: Kind
    ours: str | None  # this PR's side; None if the PR deleted the file (or binary)
    base: str | None  # the common ancestor
    theirs: str | None  # main's side; None if main deleted the file (or binary)
    before: str = ""  # lines just above the conflict, for orientation
    after: str = ""
    start_line: int | None = None  # where it starts in the PR's version of the file
    category: Category | None = None
    title: str = ""
    reason: str = ""
    recommended: Option | None = None
    proposal: str | None = None
    source: Literal["rule", "ai"] | None = None
    ai_name: str | None = None  # which AI wrote the suggestion: "Claude" or "Codex"
    choice: Option | None = None
    custom: str | None = None
    resolved: bool = False


class Segment(BaseModel):
    text: str | None = None
    conflict: str | None = None


class MergeFile(BaseModel):
    path: str
    kind: Kind
    segments: list[Segment] = Field(default_factory=list)  # text files only
    conflict_ids: list[str]
    pr_commits: list[Commit] = Field(default_factory=list)  # commits that touched it, each side
    main_commits: list[Commit] = Field(default_factory=list)


class MergeSession(BaseModel):
    base_ref: str
    base_sha: str
    head_sha: str  # your checkout's HEAD when the update started
    head_ref: str
    started_at: datetime
    status: Literal["analyzing", "ready", "committed", "failed"]
    error: str | None = None
    files: list[MergeFile] = Field(default_factory=list)
    conflicts: dict[str, Conflict] = Field(default_factory=dict)
    clean_files: list[str] = Field(default_factory=list)  # changed by main, merged by git
    commits: list[Commit] = Field(default_factory=list)  # main's commits being merged in
    commit_count: int = 0
    commit_sha: str | None = None
    hook_fixes: list[str] = Field(default_factory=list)  # files your commit hooks reformatted
    pushed: bool = False
    check_report: CheckReport | None = None
    checks_running: bool = False


# Paths and persistence

def _dir(cfg: Config, pr: PullRequest) -> Path:
    return fixwork._root(cfg, pr) / "merge"


def tree_path(cfg: Config, pr: PullRequest) -> Path:
    return _dir(cfg, pr) / "tree"


def _session_path(cfg: Config, pr: PullRequest) -> Path:
    return _dir(cfg, pr) / "session.json"


def load(cfg: Config, pr: PullRequest) -> MergeSession | None:
    p = _session_path(cfg, pr)
    return MergeSession.model_validate_json(p.read_text()) if p.exists() else None


def _save(cfg: Config, pr: PullRequest, s: MergeSession) -> None:
    p = _session_path(cfg, pr)
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(".tmp")
    tmp.write_text(s.model_dump_json())
    tmp.replace(p)


def load_current(cfg: Config, pr: PullRequest) -> MergeSession | None:
    """The session, with jobs that were cut off (the app restarted mid-way) marked as such."""
    with _lock:
        s = load(cfg, pr)
        if s and pr.ref.key not in _jobs and (s.status == "analyzing" or s.checks_running):
            if s.status == "analyzing":
                s.status, s.error = "ready", "Triage was interrupted because reviewr restarted. Try again to finish it."
            s.checks_running = False
            _save(cfg, pr, s)
        return s


def update(cfg: Config, pr: PullRequest, change) -> MergeSession:
    with _lock:
        s = load(cfg, pr)
        if s is None:
            raise MergeError("There's no update from main in progress.")
        change(s)
        _save(cfg, pr, s)
        return s


# Preview

def _fetch(repo: Path, base_ref: str) -> str | None:
    """Fetch the base branch at most every few minutes. Returns an error message."""
    key = (str(repo), base_ref)
    if time.time() - _last_fetch.get(key, 0) < FETCH_INTERVAL_S:
        return None
    proc = git._git(repo, "fetch", "--quiet", "origin", base_ref, check=False)
    if proc.returncode != 0:
        return proc.stderr.strip()
    _last_fetch[key] = time.time()
    return None


def _log(repo: Path, rng: str, *paths: str, limit: int = 30) -> list[Commit]:
    out = git._git(repo, "log", f"-n{limit}", "--format=%h%x09%an%x09%s", rng, "--", *paths, check=False).stdout
    commits = []
    for row in out.splitlines():
        parts = row.split("\t", 2)
        if len(parts) == 3:
            commits.append(Commit(sha=parts[0], author=parts[1], subject=parts[2]))
    return commits


def _count(repo: Path, rng: str) -> int:
    out = git._git(repo, "rev-list", "--count", rng, check=False).stdout.strip()
    return int(out or 0)


def _head(cfg: Config, pr: PullRequest) -> str:
    work = fixwork.existing_work_tree(cfg, pr)
    return git.head_sha(work) if work else pr.head_oid


def preview(cfg: Config, pr: PullRequest, fetch: bool = True) -> dict:
    """How far behind the base branch this PR is, and which files would conflict."""
    repo = cfg.repo_path(pr.ref.slug)
    fetch_error = _fetch(repo, pr.base_ref) if fetch else None
    base = f"origin/{pr.base_ref}"
    base_sha = git._git(repo, "rev-parse", "--verify", "--quiet", base, check=False).stdout.strip()
    if not base_sha:
        raise MergeError(f"{base} isn't in {repo}. Run: git -C {repo} fetch origin {pr.base_ref}")
    head = _head(cfg, pr)
    git.ensure_commits(repo, head)
    behind = _count(repo, f"{head}..{base_sha}")
    info = {
        "base_ref": pr.base_ref, "base_sha": base_sha, "head_sha": head, "behind": behind,
        "fetch_error": fetch_error, "conflicted_files": [], "changed_files": 0, "commits": [],
    }
    if behind == 0:
        return info
    proc = git._git(repo, "merge-tree", "--write-tree", "--name-only", "--no-messages", head, base_sha, check=False)
    if proc.returncode not in (0, 1):
        raise MergeError(f"git merge-tree failed: {proc.stderr.strip()}")
    lines = [line for line in proc.stdout.splitlines() if line.strip()]
    mb = git.merge_base(repo, head, base_sha)
    info["conflicted_files"] = lines[1:] if proc.returncode == 1 else []
    info["changed_files"] = len(git._git(repo, "diff", "--name-only", mb, base_sha).stdout.splitlines())
    info["commits"] = [c.model_dump() for c in _log(repo, f"{head}..{base_sha}", limit=20)]
    return info


# Parsing conflicts

def parse_conflicts(text: str) -> tuple[list[Segment], list[tuple[str, str, str]]]:
    """Split a file with diff3 conflict markers into plain text and conflicts.
    Returns segments (conflicts as their index, "0", "1", ...) and (ours, base, theirs)."""
    lines = text.splitlines(keepends=True)
    segments: list[Segment] = []
    found: list[tuple[str, str, str]] = []
    buf: list[str] = []
    i = 0
    while i < len(lines):
        if lines[i].startswith("<<<<<<< "):
            if buf:
                segments.append(Segment(text="".join(buf)))
                buf = []
            sides: list[list[str]] = [[], [], []]
            cur = 0
            i += 1
            while i < len(lines) and not lines[i].startswith(">>>>>>> "):
                bare = lines[i].rstrip("\r\n")
                if lines[i].startswith("||||||| ") or bare == "|||||||":
                    cur = 1
                elif bare == "=======":
                    cur = 2
                else:
                    sides[cur].append(lines[i])
                i += 1
            i += 1  # the >>>>>>> line
            segments.append(Segment(conflict=str(len(found))))
            found.append(("".join(sides[0]), "".join(sides[1]), "".join(sides[2])))
        else:
            buf.append(lines[i])
            i += 1
    if buf:
        segments.append(Segment(text="".join(buf)))
    return segments, found


def _tail(text: str, n: int) -> str:
    return "".join(text.splitlines(keepends=True)[-n:])


def _head_lines(text: str, n: int) -> str:
    return "".join(text.splitlines(keepends=True)[:n])


def _stage(tree: Path, stage: int, path: str) -> str | None:
    proc = git._git(tree, "show", f":{stage}:{path}", check=False)
    return proc.stdout if proc.returncode == 0 else None


def _unmerged(tree: Path) -> dict[str, set[int]]:
    out = git._git(tree, "ls-files", "-u", "-z").stdout
    stages: dict[str, set[int]] = {}
    for entry in filter(None, out.split("\0")):
        meta, path = entry.split("\t", 1)
        stages.setdefault(path, set()).add(int(meta.split()[2]))
    return stages


def _file_conflicts(tree: Path, path: str, stages: set[int]) -> tuple[MergeFile, list[Conflict]]:
    fid = re.sub(r"[^A-Za-z0-9]+", "-", path).strip("-")[-60:]

    def whole(kind: Kind) -> tuple[MergeFile, list[Conflict]]:
        c = Conflict(
            id=f"{fid}~0", path=path, index=0, kind=kind,
            ours=_stage(tree, 2, path) if kind != "binary" else None,
            base=_stage(tree, 1, path) if kind != "binary" else None,
            theirs=_stage(tree, 3, path) if kind != "binary" else None,
        )
        return MergeFile(path=path, kind=kind, conflict_ids=[c.id]), [c]

    if 2 not in stages:
        return whole("deleted_in_pr")
    if 3 not in stages:
        return whole("deleted_in_main")
    if Path(path).name in LOCKFILES:
        return whole("lockfile")
    try:
        text = (tree / path).read_text()
    except (UnicodeDecodeError, OSError):
        return whole("binary")
    if "\0" in text or "<<<<<<< " not in text:
        return whole("binary")

    segments, found = parse_conflicts(text)
    conflicts: list[Conflict] = []
    ours_line = 1
    for n, seg in enumerate(segments):
        if seg.text is not None:
            ours_line += seg.text.count("\n")
            continue
        k = int(seg.conflict)
        ours, base, theirs = found[k]
        prev = segments[n - 1].text if n > 0 and segments[n - 1].text else ""
        nxt = segments[n + 1].text if n + 1 < len(segments) and segments[n + 1].text else ""
        c = Conflict(
            id=f"{fid}~{k}", path=path, index=k, kind="text", ours=ours, base=base, theirs=theirs,
            before=_tail(prev, CONTEXT_LINES), after=_head_lines(nxt, CONTEXT_LINES), start_line=ours_line,
        )
        seg.conflict = c.id
        conflicts.append(c)
        ours_line += ours.count("\n")
    return MergeFile(path=path, kind="text", segments=segments, conflict_ids=[c.id for c in conflicts]), conflicts


# Rules for conflicts that need no judgement

def _squash(s: str | None) -> str:
    return re.sub(r"\s+", "", s or "")


def classify_by_rule(c: Conflict) -> None:
    def set_(category: Category, option: Option | None, title: str, reason: str) -> None:
        c.category, c.recommended, c.title, c.reason, c.source = category, option, title, reason, "rule"

    if c.kind == "deleted_in_main":
        set_("input", None, "main deleted a file this PR changed",
             "Keep the PR's version if the file is still needed; otherwise accept main's deletion.")
    elif c.kind == "deleted_in_pr":
        set_("input", None, "This PR deleted a file main changed",
             "Keep the deletion if main's change no longer matters; otherwise keep main's version.")
    elif c.kind == "binary":
        set_("input", None, "Binary file changed on both sides", "Pick one side; binary files can't be combined.")
    elif c.kind == "lockfile":
        set_("input", "theirs", "Lockfile changed on both sides",
             "Take main's lockfile, then reinstall in your checkout so this PR's dependency changes are added back, "
             "and commit the regenerated lockfile.")
    elif c.ours == c.theirs:
        set_("auto", "ours", "Both sides made the same change", "The PR and main changed these lines identically.")
    elif _squash(c.ours) == _squash(c.theirs):
        set_("auto", "ours", "Same change, different whitespace", "The two sides differ only in whitespace; the PR's formatting is kept.")
    elif _squash(c.ours) == _squash(c.base):
        set_("auto", "theirs", "Only main changed the code", "This PR only changed whitespace here, so main's change is taken.")
    elif _squash(c.theirs) == _squash(c.base):
        set_("auto", "ours", "Only this PR changed the code", "main only changed whitespace here, so the PR's change is kept.")


# Resolutions

def option_text(c: Conflict, option: Option | None) -> str | None:
    """The text of the conflicted region (or whole file) after choosing `option`."""

    def join(a: str | None, b: str | None) -> str:
        a, b = a or "", b or ""
        return a + ("\n" if a and not a.endswith("\n") and b else "") + b

    return {
        "ours": c.ours, "theirs": c.theirs, "proposal": c.proposal, "custom": c.custom,
        "ours_then_theirs": join(c.ours, c.theirs), "theirs_then_ours": join(c.theirs, c.ours),
        "delete": None,
    }.get(option or "", None)


def options_for(c: Conflict) -> list[Option]:
    if c.kind == "deleted_in_main":
        return ["ours", "delete"]
    if c.kind == "deleted_in_pr":
        return ["theirs", "delete"]
    if c.kind in ("binary", "lockfile"):
        return ["ours", "theirs"]
    opts: list[Option] = ["ours", "theirs", "ours_then_theirs", "theirs_then_ours"]
    if c.proposal is not None:
        opts.append("proposal")
    return opts + ["custom"]


def _check_text(text: str | None) -> None:
    if text and re.search(r"^(<{7}|>{7}) ", text, re.MULTILINE):
        raise MergeError("The resolution still contains conflict markers.")


def resolve(c: Conflict, choice: Option, custom: str | None = None) -> None:
    if choice == "custom":
        if custom is None:
            raise MergeError("Write the code for the custom resolution.")
        _check_text(custom)
        c.custom = custom
    elif choice not in options_for(c):
        raise MergeError(f"{choice} isn't an option for this conflict.")
    elif choice == "proposal" and c.proposal is None:
        raise MergeError("There's no proposal for this conflict yet.")
    c.choice, c.resolved = choice, True


def _write_file(tree: Path, s: MergeSession, f: MergeFile) -> None:
    """Write a file whose conflicts are all resolved, and stage it in the merge tree."""
    conflicts = [s.conflicts[i] for i in f.conflict_ids]
    if not all(c.resolved for c in conflicts):
        return
    if f.kind != "text":
        c = conflicts[0]
        if c.choice == "delete":
            git._git(tree, "rm", "--quiet", "-f", "--", f.path)
        else:
            git._git(tree, "checkout", "--ours" if c.choice == "ours" else "--theirs", "--", f.path)
            git._git(tree, "add", "--", f.path)
        return
    text = "".join(seg.text if seg.text is not None else option_text(s.conflicts[seg.conflict], s.conflicts[seg.conflict].choice) or ""
                   for seg in f.segments)
    (tree / f.path).write_text(text)
    git._git(tree, "add", "--", f.path)


def write_resolved(cfg: Config, pr: PullRequest, s: MergeSession, paths: set[str] | None = None) -> None:
    tree = tree_path(cfg, pr)
    for f in s.files:
        if paths is None or f.path in paths:
            _write_file(tree, s, f)


def file_diff(cfg: Config, pr: PullRequest, path: str) -> str:
    """The file on your branch before the merge against after it (resolutions included)."""
    return git._git(tree_path(cfg, pr), "diff", "HEAD", "--", path, check=False).stdout


# Starting, analyzing, finishing

def start(cfg: Config, pr: PullRequest, analyze) -> MergeSession:
    """Merge the base branch into a copy of your checkout and record the conflicts.
    `analyze(session, conflicts)` is run in the background for conflicts no rule settled."""
    with _lock:
        existing = load(cfg, pr)
        if existing and existing.status != "committed":
            raise MergeError("An update from main is already in progress. Finish or discard it first.")
        repo = cfg.repo_path(pr.ref.slug)
        if err := _fetch(repo, pr.base_ref):
            log.warning("fetch of %s failed: %s", pr.base_ref, err)
        work = fixwork.work_worktree(cfg, pr)
        head = git.head_sha(work)
        base_sha = git._git(repo, "rev-parse", "--verify", f"origin/{pr.base_ref}").stdout.strip()
        if _count(repo, f"{head}..{base_sha}") == 0:
            raise MergeError(f"This branch already has everything on {pr.base_ref}.")

        tree = tree_path(cfg, pr)
        git.create_draft_worktree(repo, tree, head)
        proc = git._git(tree, "-c", "merge.conflictStyle=diff3", "-c", "rerere.enabled=false", "merge",
                        "--no-commit", "--no-ff", "--no-edit", base_sha, check=False)
        stages = _unmerged(tree)
        if proc.returncode != 0 and not stages:
            git.remove_worktree(repo, tree)
            raise MergeError(f"git merge failed: {(proc.stderr or proc.stdout).strip()}")

        mb = git.merge_base(repo, head, base_sha)
        files: list[MergeFile] = []
        conflicts: dict[str, Conflict] = {}
        for path in sorted(stages):
            f, cs = _file_conflicts(tree, path, stages[path])
            f.pr_commits = _log(repo, f"{mb}..{head}", path, limit=5)
            f.main_commits = _log(repo, f"{mb}..{base_sha}", path, limit=5)
            files.append(f)
            for c in cs:
                classify_by_rule(c)
                conflicts[c.id] = c
        staged = git._git(tree, "diff", "--cached", "--name-only", "HEAD").stdout.splitlines()
        pending = [c for c in conflicts.values() if c.category is None]
        s = MergeSession(
            base_ref=pr.base_ref, base_sha=base_sha, head_sha=head, head_ref=pr.head_ref,
            started_at=datetime.now(UTC), status="analyzing" if pending else "ready",
            files=files, conflicts=conflicts, clean_files=[p for p in staged if p not in stages],
            commits=_log(repo, f"{head}..{base_sha}", limit=50), commit_count=_count(repo, f"{head}..{base_sha}"),
        )
        _save(cfg, pr, s)
    if pending:
        _jobs.add(pr.ref.key)
        _executor.submit(_analyze_job, cfg, pr, analyze, [c.id for c in pending])
    return s


def reanalyze(cfg: Config, pr: PullRequest, analyze) -> MergeSession:
    def mark(s: MergeSession) -> None:
        s.status, s.error = "analyzing", None

    s = load(cfg, pr)
    ids = [c.id for c in s.conflicts.values() if c.source != "rule" and not c.resolved] if s else []
    s = update(cfg, pr, mark)
    _jobs.add(pr.ref.key)
    _executor.submit(_analyze_job, cfg, pr, analyze, ids)
    return s


def _analyze_job(cfg: Config, pr: PullRequest, analyze, ids: list[str]) -> None:
    _jobs.add(pr.ref.key)
    try:
        s = load(cfg, pr)
        results = analyze(s, [s.conflicts[i] for i in ids])

        def apply(s: MergeSession) -> None:
            for cid, r in results.items():
                if cid in s.conflicts and not s.conflicts[cid].resolved:
                    s.conflicts[cid] = s.conflicts[cid].model_copy(update=r)
            s.status = "ready"

        update(cfg, pr, apply)
    except Exception as e:  # shown on the page; conflicts stay untriaged
        log.exception("Analyzing merge conflicts failed")
        message = str(e) or type(e).__name__

        def failed(s: MergeSession) -> None:
            s.status, s.error = "ready", f"Couldn't triage the conflicts: {message}"

        update(cfg, pr, failed)
    finally:
        _jobs.discard(pr.ref.key)


def start_checks(cfg: Config, pr: PullRequest) -> MergeSession:
    repo_cfg = cfg.repos[pr.ref.slug]
    if not repo_cfg.checks:
        raise MergeError(f'No checks are configured for {pr.ref.slug}.')
    s = load(cfg, pr)
    if not s or not all(c.resolved for c in s.conflicts.values()):
        raise MergeError("Resolve every conflict before running checks.")
    with _lock:
        write_resolved(cfg, pr, s)
    s = update(cfg, pr, lambda s: setattr(s, "checks_running", True))
    _jobs.add(pr.ref.key)
    _executor.submit(_checks_job, cfg, pr, [f.path for f in s.files])
    return s


def _checks_job(cfg: Config, pr: PullRequest, paths: list[str]) -> None:
    _jobs.add(pr.ref.key)
    tree = tree_path(cfg, pr)
    try:
        patch = git._git(tree, "diff", "HEAD", "--", *paths, check=False).stdout
        report = run_checks(cfg, pr.ref.slug, tree, patch)
    except Exception as e:
        log.exception("Checks on the merge failed to run")
        report = _failed_report(str(e))

    def save(s: MergeSession) -> None:
        s.check_report, s.checks_running = report, False

    try:
        update(cfg, pr, save)
    finally:
        _jobs.discard(pr.ref.key)


def commit(cfg: Config, pr: PullRequest, message: str) -> MergeSession:
    """Commit the merge and fast-forward your checkout of the branch to it."""
    with _lock:
        s = load(cfg, pr)
        if not s or s.status == "committed":
            raise MergeError("There's no update from main to commit.")
        if open_ := [c for c in s.conflicts.values() if not c.resolved]:
            raise MergeError(f"{len(open_)} conflict{'s' if len(open_) != 1 else ''} still unresolved.")
        work = fixwork.work_worktree(cfg, pr)
        if (now := git.head_sha(work)) != s.head_sha:
            raise MergeError(
                f"Your checkout of {pr.head_ref} moved since this update started (it's at {now[:10]}, the merge was built "
                f"on {s.head_sha[:10]}). Discard this update and start it again so the new commits are included."
            )
        tree = tree_path(cfg, pr)
        write_resolved(cfg, pr, s)
        if _unmerged(tree):
            raise MergeError("Some files are still marked as conflicted in the merge worktree.")
        s.hook_fixes = _commit_with_hooks(cfg, pr, tree, message)
        sha = git.head_sha(tree)
        ff = git._git(work, "merge", "--ff-only", sha, check=False)
        if ff.returncode != 0:
            raise MergeError(
                "The merge is committed but your checkout couldn't be moved to it: "
                + (ff.stderr or ff.stdout).strip()
                + f"\nCommit or stash those changes and try again, or run: git -C {work} merge --ff-only {sha[:12]}"
            )
        s.status, s.commit_sha = "committed", sha
        _save(cfg, pr, s)
        git.remove_worktree(cfg.repo_path(pr.ref.slug), tree)
        return s


def _commit_with_hooks(cfg: Config, pr: PullRequest, tree: Path, message: str) -> list[str]:
    """The merge commit, with your commit hooks (see fixwork.commit_with_hooks)."""
    try:
        return fixwork.commit_with_hooks(cfg, pr.ref.slug, tree, message)[1]
    except git.GitError as e:
        raise MergeError(str(e).replace("Fix what they report, then try again.", "Fix what they report, or adjust the resolution, then commit again.")) from e


def push(cfg: Config, pr: PullRequest) -> MergeSession:
    s = load(cfg, pr)
    if not s or s.status != "committed":
        raise MergeError("Commit the merge before pushing.")
    git.push(fixwork.work_worktree(cfg, pr), pr.head_ref)
    return update(cfg, pr, lambda s: setattr(s, "pushed", True))


def discard(cfg: Config, pr: PullRequest) -> None:
    """Throw away the merge worktree and the session. Your checkout was never touched."""
    with _lock:
        repo = cfg.repo_path(pr.ref.slug)
        tree = tree_path(cfg, pr)
        if tree.exists():
            git._git(tree, "merge", "--abort", check=False)
            git.remove_worktree(repo, tree)
        shutil.rmtree(_dir(cfg, pr), ignore_errors=True)
        git._git(repo, "worktree", "prune", check=False)

